"""Write the generated C for a whole module: header, one file per segment, and tables."""
import os
from collections import defaultdict
from pathlib import Path

from . import flags as F
from .emit import EmitError, FunctionEmitter
from .ne import Import


class ModuleEmitter:
    def __init__(self, prog, mod, outdir, overrides=()):
        self.prog = prog
        self.mod = mod                    # C identifier prefix, e.g. "play_e"
        self.out = Path(outdir)
        self.overrides = set(overrides)   # entries implemented by hand in the runtime
        self.imports = {}                 # Import -> index

    def import_index(self, imp):
        if imp not in self.imports:
            self.imports[imp] = len(self.imports)
        return self.imports[imp]

    def fname(self, seg, off):
        return f"{self.mod}_{seg:03d}_{off:04x}"

    def run(self):
        prog, mod = self.prog, self.mod
        bodies = prog.all_bodies()
        live, entry_live, ret_live, violations = F.analyze(prog, bodies)
        if os.environ.get("RECOMP_ALL_FLAGS"):   # debugging: compute every flag everywhere
            live = {e: {a: F.ALL for a in bodies[e].insns} for e in bodies}
        self.out.mkdir(parents=True, exist_ok=True)

        by_seg = defaultdict(list)
        for entry in sorted(bodies):
            by_seg[entry[0]].append(entry)

        errors, written = [], []
        for seg, entries in sorted(by_seg.items()):
            lines = [f'#include "{mod}.h"', ""]
            for entry in entries:
                body = bodies[entry]
                name = prog.functions[entry]
                if entry in self.overrides:
                    lines.append(f"/* {name}: implemented by hand in the runtime */")
                    continue
                em = FunctionEmitter(mod, prog, body, live[entry])
                em.imports = self.import_index
                try:
                    code = em.emit()
                except EmitError as e:
                    errors.append(f"{name} ({seg}:{entry[1]:04x}): {e}")
                    code = [f'    rt_trap(c, "not recompiled: {str(e)[:60]}", SEL({seg}), {entry[1]:#x});']
                lines.append(f"/* {name} */")
                lines.append(f"void {self.fname(*entry)}(CPU *c)")
                lines.append("{")
                lines += code
                lines.append("}")
                lines.append("")
            path = self.out / f"{mod}_seg{seg:03d}.c"
            path.write_text("\n".join(lines), newline="\n")
            written.append(path)

        self.write_header(bodies)
        self.write_tables(bodies)
        return {
            "functions": len(bodies),
            "instructions": sum(len(b.insns) for b in bodies.values()),
            "files": len(written) + 2,
            "imports": len(self.imports),
            "errors": errors,
            "flag_violations": violations,
        }

    def write_header(self, bodies):
        mod = self.mod
        nseg = max(self.prog.ne.segments)
        lines = [
            f"/* Generated by tools/recompile.py from {Path(self.prog.ne.path).name}. Do not edit. */",
            "#pragma once",
            '#include "recomp.h"',
            "",
            f"extern uint16_t {mod}_sel[{nseg + 1}];",
            f"extern uint32_t {mod}_import_addr[{max(len(self.imports), 1)}];",
            f"extern const RecompModule {mod}_module;",
            "",
            f"#define SEL(n) {mod}_sel[n]",
            f"#define IMPCALL(i) rt_import(c, &{mod}_module, i)",
            f"#define IMPADDR(i) {mod}_import_addr[i]",
            "",
        ]
        lines += [f"void {self.fname(*e)}(CPU *c);" for e in sorted(bodies)]
        (self.out / f"{mod}.h").write_text("\n".join(lines) + "\n", newline="\n")

    def write_tables(self, bodies):
        mod = self.mod
        nseg = max(self.prog.ne.segments)
        imports = sorted(self.imports.items(), key=lambda kv: kv[1])
        labels = {(i["module"], i["ordinal"]): i["name"] for i in self.prog.analysis["imports"]}
        n = max(len(imports), 1)
        lines = [f'#include "{mod}.h"', "",
                 f"uint16_t {mod}_sel[{nseg + 1}];",
                 f"static uint16_t import_slot[{n}];",
                 f"uint32_t {mod}_import_addr[{n}];", "",
                 f"static const RecompImport imports[{n}] = {{"]
        for imp, idx in imports:
            name = f'"{imp.name}"' if imp.name else "NULL"
            label = labels.get((imp.module, imp.ordinal)) or imp.name
            label = f'"{label}"' if label else "NULL"
            lines.append(f'    {{"{imp.module}", {imp.ordinal or 0}, {name}, {label}}},  /* {idx} */')
        if not imports:
            lines.append("    {0}")
        lines += ["};", "", f"static const RecompFunc funcs[{len(bodies)}] = {{"]
        lines += [f"    {{{s}, {o:#06x}, {self.fname(s, o)}}}," for s, o in sorted(bodies)]
        image = Path(self.prog.ne.path).read_bytes()
        h = 0xCBF29CE484222325                      # FNV-1a 64, checked by the runtime loader
        for b in image:
            h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
        lines += ["};", "",
                  f"const RecompModule {mod}_module = {{",
                  f'    "{self.prog.ne.name}", {mod}_sel, {nseg}, funcs, {len(bodies)},',
                  f"    imports, import_slot, {mod}_import_addr, {len(imports)},",
                  f"    {len(image)}u, {h:#018x}ull",
                  "};", ""]
        (self.out / f"{mod}_tables.c").write_text("\n".join(lines), newline="\n")
